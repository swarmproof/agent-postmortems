#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = ["pyyaml", "jsonschema"]
# ///
"""Generate the corpus-derived blocks in README.md and TAXONOMY.md from the live corpus.

Two blocks are maintained, each between a START/END marker pair so the text around
them stays hand-written while the numbers and examples can never drift from the data:

  README.md    <!-- STATS:START ... -->    the "What's in the corpus" stat rows
  TAXONOMY.md  <!-- EXAMPLES:START ... --> one example incident per failure class

Run in CI by publish.yml on every merge, alongside the export rebuild.

Usage:
  uv run scripts/gen_readme_stats.py            # rewrite both files in place
  uv run scripts/gen_readme_stats.py --check    # exit 1 if either file is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_exports import load_incidents  # noqa: E402  same record set the export publishes

REPO = Path(__file__).resolve().parent.parent
TAXONOMY = REPO / "schema" / "taxonomy.yaml"
README = REPO / "README.md"
TAXONOMY_MD = REPO / "TAXONOMY.md"
SITE = "https://swarmproof.github.io/agent-postmortems"

START = "<!-- STATS:START — auto-generated by scripts/gen_readme_stats.py; do not edit by hand -->"
END = "<!-- STATS:END -->"
EX_START = "<!-- EXAMPLES:START — auto-generated by scripts/gen_readme_stats.py; do not edit by hand -->"
EX_END = "<!-- EXAMPLES:END -->"


def load_records() -> list[dict]:
    """The records exactly as export/incidents.json is built from them."""
    return load_incidents()


def corpus_counts(records: list[dict]) -> dict[str, int]:
    """Record totals by incident_type; the single source for every published count."""
    return {
        "total": len(records),
        "incident": sum(1 for r in records if r.get("incident_type") == "incident"),
        "hazard": sum(1 for r in records if r.get("incident_type") == "hazard"),
    }


def counts_sentence(counts: dict[str, int]) -> str:
    return (
        f"{counts['total']} sourced records: {counts['incident']} realized incidents "
        f"and {counts['hazard']} demonstrated hazards"
    )


def taxonomy_classes() -> list[str]:
    """Class names in taxonomy.yaml order (the authority file's order, not alphabetical)."""
    return [c["name"] for c in yaml.safe_load(TAXONOMY.read_text())["classes"]]


def compute_rows(records: list[dict]) -> str:
    years = [int(str(r["date"])[:4]) for r in records if r.get("date")]
    span = f"{min(years)}–{max(years)}" if years else ""

    present = set()
    for r in records:
        present.add(r.get("primary_failure_class"))
        present.update(fc["class"] for fc in r.get("failure_classes", []))
    all_classes = set(taxonomy_classes())
    covered = len(present & all_classes)

    cve = sum(1 for r in records if r.get("cve"))

    return (
        f"{START}\n"
        f"| **Records** | {counts_sentence(corpus_counts(records))} ({span}) |\n"
        f"| **Coverage** | {covered} of {len(all_classes)} failure classes; {cve} CVE-backed |\n"
        f"{END}"
    )


def compute_examples(records: list[dict]) -> str:
    """One bullet per taxonomy class: record count and the earliest example by primary class.

    The example is chosen deterministically — earliest `date`, then lowest `incident_id` —
    so reruns on an unchanged corpus produce byte-identical output.
    """
    by_class: dict[str, list[dict]] = {}
    for r in records:
        by_class.setdefault(r.get("primary_failure_class"), []).append(r)

    lines = [EX_START]
    for name in taxonomy_classes():
        recs = by_class.get(name, [])
        if not recs:
            lines.append(f"- `{name}` — no record yet")
            continue
        ex = min(recs, key=lambda r: (str(r.get("date", "")), r["incident_id"]))
        iid = ex["incident_id"]
        title = " ".join(str(ex.get("title", "")).split())
        n = len(recs)
        lines.append(
            f"- `{name}` — {n} record{'s' if n != 1 else ''}; "
            f"e.g. [`{iid}`]({SITE}/{iid}/): {title}"
        )
    lines.append(EX_END)
    return "\n".join(lines)


def splice(text: str, start: str, end: str, block: str) -> str:
    return re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _m: block, text, flags=re.DOTALL)


def main() -> int:
    records = load_records()
    targets = [
        (README, START, END, compute_rows(records), "README stats"),
        (TAXONOMY_MD, EX_START, EX_END, compute_examples(records), "TAXONOMY examples"),
    ]
    check = "--check" in sys.argv
    stale = []
    for path, start, end, block, label in targets:
        text = path.read_text()
        if start not in text or end not in text:
            print(f"error: {label} markers not found in {path.name}", file=sys.stderr)
            return 2
        new = splice(text, start, end, block)
        if new == text:
            continue
        if check:
            stale.append(label)
            continue
        path.write_text(new)
        print(f"{label} regenerated")

    if check:
        if stale:
            print(f"out of date: {', '.join(stale)} — run: uv run scripts/gen_readme_stats.py")
            return 1
        print("README stats and TAXONOMY examples up to date")
        return 0
    print("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
